#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Mirror local-only artefacts onto an orphan branch, so they get backed up
without ever touching the publishable history on ``main``.

The problem
-----------
``data/``, ``runs/`` and ``archive/`` hold derived market data and per-instrument
verdicts. They must not be published (re-distribution rights; investment-advice
compliance). They also must not live only on one disk (``git`` cannot forget a
blob once it is in a public history, but a dead SSD forgets everything).

The split
---------
* ``main``          -> code only. This is the branch that can be made public.
* ``local-backup``  -> an orphan branch: snapshot of code *plus* the private
                       artefacts. Pushed only to a private remote.

Because the branch is orphaned it shares no history with ``main``, so a later
``git push --force`` of one can never drag the other with it.

How it works
------------
A detached ``git worktree`` is created outside the repository, the artefacts are
copied in, and a commit is made there. Your working tree on ``main`` is never
touched, so the script is safe to run while you have edits in progress.

Usage
-----
    python scripts/backup_private_data.py --dry-run        # show what would happen
    python scripts/backup_private_data.py                  # commit locally
    python scripts/backup_private_data.py --push           # commit and push

Requires a git remote before ``--push`` works (``git remote add origin ...``).
"""
import argparse
import os
import shutil
import subprocess
import sys
from datetime import datetime

BRANCH = "local-backup"
DEFAULT_DIRS = ("data", "runs", "archive", "drafts")
# Kept deliberately tiny: this branch is for storage, not for development.
BACKUP_IGNORE = """\
__pycache__/
*.py[cod]
*.egg-info/
.pytest_cache/
.venv/
venv/
.DS_Store
Thumbs.db
"""

BACKUP_NOTE = """\
# local-backup branch

Snapshot of artefacts that are **not** publishable and therefore absent from
`main`:

- `data/` - derived market data (re-distribution rights belong to the vendors)
- `runs/`, `archive/`, `drafts/` - per-instrument verdicts and working notes

Generated by `scripts/backup_private_data.py`. Do not develop here; edit on
`main` and re-run the script.

This branch is orphaned on purpose: it shares no history with `main`, so it can
never be pushed to a public remote by accident, and a force-push of one branch
cannot affect the other.
"""


def git(args, cwd, check=True):
    proc = subprocess.run(["git"] + args, cwd=cwd, capture_output=True, text=True,
                          encoding="utf-8", errors="replace")
    if check and proc.returncode != 0:
        raise RuntimeError("git %s failed (%d): %s%s"
                           % (" ".join(args), proc.returncode,
                              proc.stdout.strip(), proc.stderr.strip()))
    return proc


def repo_root():
    proc = git(["rev-parse", "--show-toplevel"], cwd=os.getcwd())
    return proc.stdout.strip()


def branch_exists(root, branch):
    return git(["rev-parse", "--verify", "--quiet", "refs/heads/" + branch],
               cwd=root, check=False).returncode == 0


def copy_tree(src, dst, dry_run):
    """Copy src into dst/<basename>; returns (file_count, bytes)."""
    target = os.path.join(dst, os.path.basename(src.rstrip("/\\")))
    count = size = 0
    for dirpath, _dirnames, filenames in os.walk(src):
        rel = os.path.relpath(dirpath, src)
        for fn in filenames:
            if fn.endswith((".pyc", ".pyo")):
                continue
            full = os.path.join(dirpath, fn)
            try:
                size += os.path.getsize(full)
            except OSError:
                continue
            count += 1
            if dry_run:
                continue
            out_dir = target if rel == "." else os.path.join(target, rel)
            os.makedirs(out_dir, exist_ok=True)
            shutil.copy2(full, os.path.join(out_dir, fn))
    return count, size


def sync_code(root, dst, dry_run):
    """Copy every file tracked on the current branch into the backup worktree.

    Without this, the backup branch would freeze the code as it looked when the
    branch was first created -- a restore would bring back month-old logic. It
    also keeps the commit hook in the worktree current.
    """
    proc = git(["ls-files", "-z"], cwd=root)
    paths = [p for p in proc.stdout.split("\0") if p.strip()]
    copied = 0
    for rel in paths:
        src = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.isfile(src):
            continue
        copied += 1
        if dry_run:
            continue
        out = os.path.join(dst, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        shutil.copy2(src, out)
    return copied


def main(argv=None):
    ap = argparse.ArgumentParser(description="Back up private artefacts to an orphan branch.")
    ap.add_argument("--dirs", default=",".join(DEFAULT_DIRS),
                    help="comma-separated directories to mirror (default: %s)" % ",".join(DEFAULT_DIRS))
    ap.add_argument("--branch", default=BRANCH, help="backup branch name")
    ap.add_argument("--worktree", default="",
                    help="worktree path (default: sibling of the repo, hidden)")
    ap.add_argument("--push", action="store_true", help="push the branch to origin after committing")
    ap.add_argument("--dry-run", action="store_true", help="report actions without writing or committing")
    args = ap.parse_args(argv)

    root = repo_root()
    dirs = [d.strip() for d in args.dirs.split(",") if d.strip()]
    present = [d for d in dirs if os.path.isdir(os.path.join(root, d))]
    skipped = [d for d in dirs if d not in present]

    wt = args.worktree or os.path.join(os.path.dirname(root),
                                       ".%s-%s" % (os.path.basename(root), args.branch))

    print("[backup] repo      : %s" % root)
    print("[backup] branch    : %s" % args.branch)
    print("[backup] worktree  : %s" % wt)
    print("[backup] mirror    : %s" % (", ".join(present) or "(nothing found)"))
    if skipped:
        print("[backup] skipped   : %s (absent)" % ", ".join(skipped))
    if not present:
        print("[backup] nothing to back up")
        return 0

    if args.dry_run:
        total_files = total_bytes = 0
        for d in present:
            n, b = copy_tree(os.path.join(root, d), wt, dry_run=True)
            total_files += n
            total_bytes += b
            print("[backup]   %-8s %5d files  %8.1f MB" % (d, n, b / 1048576.0))
        code_n = sync_code(root, wt, dry_run=True)
        print("[backup]   code     %5d files  (tracked on current branch)" % code_n)
        print("[backup] dry-run: would copy %d files, %.1f MB"
              % (total_files, total_bytes / 1048576.0))
        return 0

    # -- prepare the worktree ------------------------------------------------
    # A worktree whose directory disappeared stays registered and blocks
    # re-creation. `prune` alone keeps recent entries (gc.worktreePruneExpire),
    # so expire it immediately and drop any stale registration for our path.
    git(["worktree", "prune", "--expire", "now"], cwd=root, check=False)
    git(["worktree", "remove", "--force", wt], cwd=root, check=False)
    if branch_exists(root, args.branch):
        print("[backup] reusing branch %s" % args.branch)
        git(["worktree", "add", wt, args.branch], cwd=root)
    else:
        if os.path.isdir(wt):
            shutil.rmtree(wt)
        git(["worktree", "add", "--detach", wt, "HEAD"], cwd=root)
        git(["checkout", "--orphan", args.branch], cwd=wt)
        print("[backup] created orphan branch %s" % args.branch)

    # -- copy artefacts ------------------------------------------------------
    code_n = sync_code(root, wt, dry_run=False)
    print("[backup]   synced   code      %5d files" % code_n)

    total_files = 0
    for d in present:
        n, _b = copy_tree(os.path.join(root, d), wt, dry_run=False)
        total_files += n
        print("[backup]   copied %-8s %5d files" % (d, n))

    # On this branch the artefacts are legitimately tracked, so the ignore rules
    # are minimal and local to the branch.
    with open(os.path.join(wt, ".gitignore"), "w", encoding="utf-8") as f:
        f.write(BACKUP_IGNORE)
    note = os.path.join(wt, "LOCAL_BACKUP.md")
    if not os.path.exists(note):
        with open(note, "w", encoding="utf-8") as f:
            f.write(BACKUP_NOTE)

    git(["add", "-A"], cwd=wt)
    staged = git(["diff", "--cached", "--name-only"], cwd=wt).stdout.strip()
    if not staged:
        print("[backup] no changes; branch already up to date")
    else:
        stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
        git(["commit", "-q", "-m",
             "backup: local data snapshot %s\n\nPrivate artefacts mirrored from main; "
             "never pushed to a public remote.\nFiles: %d" % (stamp, total_files)], cwd=wt)
        print("[backup] committed: %s" % git(["rev-parse", "--short", "HEAD"], cwd=wt).stdout.strip())

    if args.push:
        remotes = git(["remote"], cwd=wt).stdout.split()
        if not remotes:
            print("[backup] ERROR: no git remote configured; add one, then re-run with --push")
            return 2
        git(["push", "-u", "origin", args.branch], cwd=wt)
        print("[backup] pushed %s -> origin" % args.branch)
    else:
        print("[backup] local only (add --push to upload)")

    print("[backup] restore with: git worktree add ./restore %s" % args.branch)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except RuntimeError as exc:
        sys.stderr.write("[backup] FAILED: %s\n" % exc)
        raise SystemExit(1)
